import numpy as np
import matplotlib.pyplot as plt

class System:
    def __init__(self, num_particles, x, v, m, G):
        self.num_particles = num_particles
        self.x = x
        self.v = v
        self.m = m
        self.G = G
    
    def com_correction(self):
        """
        Shift the system so that the center of mass (CoM) is at the origin and the net velocity of 
        the system is zero.
        
        This prevents the whole system from drifting in space
        due to numerical or initial condition offsets.
        """        

        x_cm = np.zeros(3)            
        v_cm = np.zeros(3)
        M = 0.0

        for i in range(self.num_particles):
            x_cm += self.m[i] * self.x[i]
            v_cm += self.m[i] * self.v[i]
            M += self.m[i]
        
        x_cm /= M
        v_cm /= M

        self.x -= x_cm
        self.v -= v_cm

