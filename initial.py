def plot_initial_conditions(system, labels, colors, legend):
    fig, ax = plt.subplots()

    ax.set_xlabel("$x$ (AU)")
    ax.set_ylabel("$y$ (AU)")

    for i in range(system.num_particles):
        ax.scatter(system.x[i, 0], system.x[i, 1], marker="o", color=colors[i], label=labels[i])

    if legend:
        ax.legend()
    
    plt.show()

def acceleration(a, system):
    """
    Computing the gravitational acceleration using Newton's law of gravitation
    """
    a.fill(0.0)

    x = system.x
    m = system.m
    G = system.G
    N = system.num_particles

    for i in range(N):
        for j in range(i + 1, N):
            r = x[j] - x[i]
            dist = np.linalg.norm(r)

            factor = G / dist ** 3

            a[i] += factor * m[j] * r
            a[j] -= factor * m[i] * r
